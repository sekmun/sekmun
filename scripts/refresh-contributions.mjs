// Pulls the last 12 months of contributions from the GitHub GraphQL API into data/contributions.json.
// Needs GITHUB_TOKEN (the Actions token is enough). Private contributions are counted
// only if "Include private contributions on my profile" is switched on in GitHub settings.
import { writeFileSync } from "node:fs";

const login = process.env.GH_LOGIN || "sekmun";
const token = process.env.GITHUB_TOKEN;
if (!token) throw new Error("GITHUB_TOKEN is not set");

const query = `query($login:String!){user(login:$login){contributionsCollection{contributionCalendar{
  totalContributions weeks{contributionDays{date contributionCount}}}}}}`;

const res = await fetch("https://api.github.com/graphql", {
  method: "POST",
  headers: { Authorization: `bearer ${token}`, "Content-Type": "application/json", "User-Agent": "sekmun-site" },
  body: JSON.stringify({ query, variables: { login } }),
});
const json = await res.json();
if (!res.ok || json.errors) throw new Error(JSON.stringify(json.errors || json));

const cal = json.data.user.contributionsCollection.contributionCalendar;
const all = cal.weeks.flatMap((w) => w.contributionDays);
const days = Object.fromEntries(all.filter((d) => d.contributionCount > 0).map((d) => [d.date, d.contributionCount]));

writeFileSync(
  new URL("../data/contributions.json", import.meta.url),
  JSON.stringify(
    {
      _note: "Generated by scripts/refresh-contributions.mjs. Days not listed are 0.",
      login,
      from: all[0].date,
      to: all[all.length - 1].date,
      days,
    },
    null,
    2,
  ) + "\n",
);
console.log(`${cal.totalContributions} contributions, ${all[0].date} to ${all[all.length - 1].date}`);
